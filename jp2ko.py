def _final(s, idx):
    if not s: return s
    c = s[-1]; o = ord(c) - 0xAC00
    if 0 <= o < 11172 and o % 28 == 0: return s[:-1] + chr(ord(c) + idx)
    return s

def _kana2hangul(h):
    h = "".join(chr(ord(c) - 0x60) if "ァ" <= c <= "ヶ" else c for c in h)
    out = ""; i = 0; first = True; prev_v = ""
    while i < len(h):
        c = h[i]
        if c == "ー": i += 1; continue
        if c == "っ":
            nx = h[i + 1:i + 2]
            if nx == "く":
                out = _final(out, 1); i += 1
                if nx == "く" and (i + 1 >= len(h) or h[i + 1] in "すしとーぷ"): i += 1
                continue
            out = _final(out, 19); i += 1; continue
        if c == "ん": out = _final(out, 4); i += 1; prev_v = ""; continue
        if c == "う" and prev_v in ("o", "u"): i += 1; prev_v = ""; continue
        two = h[i:i + 2]
        if two in _ROW: v = _ROW[two]; i += 2
        elif c in _ROW: v = _ROW[c]; i += 1
        else: out += c; i += 1; first = True; prev_v = ""; continue
        out += v[0] if (first or len(v) == 1) else v[1]
        vv = v[0]; o = ord(vv) - 0xAC00; med = (o // 28) % 21 if 0 <= o < 11172 else -1
        prev_v = "o" if med in (8, 12) else "u" if med in (13, 17, 18) else ""
        first = False
    return out

